		String getAnimalAscii(String animal) {
			return switch (animal) {
		    case "MOUSE" -> mouse;
		    case "MONKEY" -> monkey;
		    case "CHIMPANZEE" -> chimpanzee;
		    case "ORANGUTAN" -> orangutan;
		    case "BEAR" -> bear;
		    case "GORILLA" -> gorilla;
		    case "JELLYFISH" -> jellyfish;
		    case "TORTOISE" -> tortoise;
		    case "CAT" -> cat;
		    case "WOLF" -> wolf;
		    case "TIGER" -> tiger;
		    case "CROCODILE" -> crocodile;
		    case "SLOTH" -> sloth;
		    case "CHICKEN" -> chicken;
		    case "DEER" -> deer;
		    case "KANGAROO" -> kangaroo;
		    case "GREYHOUND" -> greyhound;
		    case "CHEETAH" -> cheetah;
		    case "SNAIL" -> snail;
		    case "FROG" -> frog;
		    case "RABBIT" -> rabbit;
		    case "ZEBRA" -> zebra;
		    case "GAZELLE" -> gazelle;
		    case "STALLION" -> stallion;
		    case "PANDA" -> panda;
		    case "PENGUIN" -> penguin;
		    case "DOG" -> dog;
		    case "FOX" -> fox;
		    case "HUSKY" -> husky;
		    case "KOALA" -> koala;
		    case "SQUIRREL" -> squirrel;
		    case "BOBCAT" -> bobcat;
		    case "MOUNTAIN_GOAT" -> mountainGoat;
		    case "SNOW_LEOPARD" -> snowLeopard;
		    default -> "Animal not found.";
		};
		}
	
